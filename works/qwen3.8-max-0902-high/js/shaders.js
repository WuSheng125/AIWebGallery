'use strict';

/* ================================================================
 *  着色器库
 *  核心：黑洞光线步进（Schwarzschild 光子测地线）
 *  参考物理：du/dφ 形式的光子轨道方程 d²u/dφ² = 1.5·rs·u²
 *  在笛卡尔坐标下的等价加速度形式：a = -1.5·rs·h²·r⃗ / |r⃗|⁵
 *  其中 h = |r⃗ × v⃗| 为守恒的比角动量。
 * ================================================================ */

/* ---------- 全屏三角形顶点着色器（所有 pass 共用） ---------- */
var VS_QUAD = [
  '#version 300 es',
  'out vec2 vUv;',
  'void main() {',
  '  vec2 p = vec2(float((gl_VertexID << 1) & 2), float(gl_VertexID & 2));',
  '  vUv = p;',
  '  gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);',
  '}'
].join('\n');

/* ---------- 主 pass：黑洞光线步进 ---------- */
var FS_RAYMARCH = [
  '#version 300 es',
  'precision highp float;',
  'precision highp int;',
  '',
  'in vec2 vUv;',
  'out vec4 fragColor;',
  '',
  'uniform vec3  uCamPos;',
  'uniform vec3  uCamRight;',
  'uniform vec3  uCamUp;',
  'uniform vec3  uCamFwd;',
  'uniform float uTanHalfFov;',
  'uniform float uAspect;',
  'uniform float uPhase;        // 吸积盘旋转相位（CPU 累积）',
  '',
  'uniform float uMass;         // 事件视界半径 rs（场景单位）',
  'uniform float uLensing;      // 引力透镜强度倍率（1 = 物理真实）',
  'uniform float uDiskInner;    // 盘内半径（× rs）',
  'uniform float uDiskOuter;    // 盘外半径（× rs）',
  'uniform float uDiskBright;',
  'uniform float uDiskTemp;     // 色温 0..1（红→金→白→蓝白）',
  'uniform float uDoppler;      // 多普勒聚束/频移强度 0..1',
  'uniform float uDiskThick;    // 盘面厚度（掠射增亮系数）',
  'uniform float uTilt;         // 盘面倾角（弧度）',
  '',
  'uniform float uStarDensity;',
  'uniform float uStarBright;',
  'uniform float uNebula;',
  '',
  'uniform int   uSteps;',
  '',
  '/* ---- 哈希与值噪声 ---- */',
  'float hash13(vec3 p3) {',
  '  p3 = fract(p3 * 0.1031);',
  '  p3 += dot(p3, p3.zyx + 31.32);',
  '  return fract((p3.x + p3.y) * p3.z);',
  '}',
  '',
  'float vnoise(vec3 x) {',
  '  vec3 i = floor(x);',
  '  vec3 f = fract(x);',
  '  f = f * f * (3.0 - 2.0 * f);',
  '  float n00 = mix(hash13(i),                    hash13(i + vec3(1.0, 0.0, 0.0)), f.x);',
  '  float n01 = mix(hash13(i + vec3(0.0, 1.0, 0.0)), hash13(i + vec3(1.0, 1.0, 0.0)), f.x);',
  '  float n10 = mix(hash13(i + vec3(0.0, 0.0, 1.0)), hash13(i + vec3(1.0, 0.0, 1.0)), f.x);',
  '  float n11 = mix(hash13(i + vec3(0.0, 1.0, 1.0)), hash13(i + vec3(1.0, 1.0, 1.0)), f.x);',
  '  return mix(mix(n00, n01, f.y), mix(n10, n11, f.y), f.z);',
  '}',
  '',
  'float fbm4(vec3 p) {',
  '  float v = 0.0;',
  '  float a = 0.5;',
  '  for (int o = 0; o < 4; o++) {',
  '    v += a * vnoise(p);',
  '    p = p * 2.03 + 13.7;',
  '    a *= 0.5;',
  '  }',
  '  return v;',
  '}',
  '',
  'float fbm3(vec3 p) {',
  '  float v = 0.0;',
  '  float a = 0.5;',
  '  for (int o = 0; o < 3; o++) {',
  '    v += a * vnoise(p);',
  '    p = p * 2.03 + 13.7;',
  '    a *= 0.5;',
  '  }',
  '  return v;',
  '}',
  '',
  'mat3 rotX(float ang) {',
  '  float s = sin(ang), c = cos(ang);',
  '  return mat3(1.0, 0.0, 0.0,',
  '              0.0, c,   s,',
  '              0.0, -s,  c);',
  '}',
  '',
  '/* ---- 吸积盘色温渐变（近似黑体辐射色） ---- */',
  'vec3 diskRamp(float t) {',
  '  t = clamp(t, 0.0, 1.0);',
  '  vec3 c;',
  '  if (t < 0.25)      c = mix(vec3(0.30, 0.02, 0.01), vec3(0.85, 0.22, 0.04), t * 4.0);',
  '  else if (t < 0.50) c = mix(vec3(0.85, 0.22, 0.04), vec3(1.00, 0.60, 0.22), (t - 0.25) * 4.0);',
  '  else if (t < 0.75) c = mix(vec3(1.00, 0.60, 0.22), vec3(1.00, 0.90, 0.72), (t - 0.50) * 4.0);',
  '  else               c = mix(vec3(1.00, 0.90, 0.72), vec3(0.70, 0.82, 1.00), (t - 0.75) * 4.0);',
  '  return c;',
  '}',
  '',
  '/* ---- 吸积盘采样：密度噪声 + 相对论多普勒 ---- */',
  'vec4 sampleDisk(vec3 p, float r, vec3 rayDir, float rs, float ri, float ro) {',
  '  float t = (r - ri) / max(ro - ri, 1e-4);',
  '  if (t < 0.0 || t > 1.0) return vec4(0.0);',
  '',
  '  // 径向密度：亮度集中于内区，向外迅速衰减（电影质感关键）',
  '  float radial = smoothstep(0.0, 0.05, t) * pow(1.0 - t, 2.2);',
  '  radial += 0.6 * exp(-t * 4.5);',
  '  if (radial < 0.015) return vec4(0.0);',
  '',
  '  // 开普勒差速旋转剪切出湍流纹理',
  '  float ang = atan(p.z, p.x);',
  '  float rr = r / rs;',
  '  float omega = 1.6 / (rr * sqrt(rr) + 0.6);',
  '  float a = ang - uPhase * omega;',
  '  float rrEff = rr + uPhase * 0.05;   // 物质缓慢内落的漂移',
  '  vec3 np = vec3(cos(a), sin(a), 0.0) * (rrEff * 0.85) + vec3(0.0, 0.0, rrEff * 0.55);',
  '  float n1 = fbm4(np * 2.2);',
  '  // 剪切流将湍流拉伸为周向细纹（唱片纹状丝状结构）',
  '  vec3 gp = vec3(cos(a), sin(a), 0.0) * (rr * 1.1) + vec3(0.0, 0.0, rr * 3.0);',
  '  float g = fbm3(gp * 1.6);',
  '  float density = radial * (0.72 + 0.33 * n1) * (0.70 + 0.45 * g);',
  '  density = max(density, 0.0);',
  '',
  '  // 掠射角穿过薄盘 → 光程更长 → 更亮（薄盘体积效应近似）',
  '  float graze = clamp(1.0 / max(abs(normalize(rayDir).y), 0.05), 1.0, 1.0 + 3.0 * uDiskThick);',
  '  density *= graze;',
  '',
  '  // 相对论多普勒：运动物质朝观察者方向聚束增亮、蓝移；反向变暗、红移',
  '  vec3 tang = normalize(vec3(-p.z, 0.0, p.x));       // 轨道切向速度方向',
  '  float beta = clamp(sqrt(0.62 * rs / r), 0.0, 0.92); // 近圆轨道速度（略夸张以强化电影感）',
  '  vec3 emitDir = -normalize(rayDir);                 // 光子飞向观察者的方向',
  '  float mu = dot(tang, emitDir) * beta;',
  '  float gamma = inversesqrt(max(1.0 - beta * beta, 1e-4));',
  '  float dopp = clamp(1.0 / (gamma * (1.0 - mu)), 0.05, 20.0);',
  '  float doppEff = mix(1.0, dopp, uDoppler);',
  '  float beam = pow(doppEff, 3.0);                    // 相对论性聚束 ∝ δ³',
  '  float tempEff = clamp(uDiskTemp + (doppEff - 1.0) * 0.45, 0.0, 1.0);',
  '  tempEff = clamp(tempEff + (1.0 - t) * 0.10, 0.0, 1.0);   // 内缘更炽白',
  '',
  '  vec3 col = diskRamp(tempEff) * (density * uDiskBright * 1.05 * beam);',
  '  return vec4(col, density);',
  '}',
  '',
  '/* ---- 程序化星空 ---- */',
  'vec3 starLayer(vec3 d, float scale, float seed, float densK, float sharp) {',
  '  vec3 c = d * scale;',
  '  vec3 ic = floor(c);',
  '  vec3 fc = fract(c) - 0.5;',
  '  float thr = 1.0 - uStarDensity * densK;',
  '  float hs = hash13(ic + seed);',
  '  vec3 col = vec3(0.0);',
  '  if (hs > thr) {',
  '    vec3 offs = vec3(hash13(ic + seed + 11.3),',
  '                     hash13(ic + seed + 27.7),',
  '                     hash13(ic + seed + 41.9)) - 0.5;',
  '    vec3 dv = fc - offs * 0.7;',
  '    float dd = dot(dv, dv);',
  '    float mag = (hs - thr) / max(1.0 - thr, 1e-4);',
  '    vec3 sc = mix(vec3(1.0, 0.88, 0.74), vec3(0.72, 0.83, 1.0), hash13(ic + seed + 63.1));',
  '    float core = exp(-dd * 380.0 * sharp);',
  '    float halo = exp(-dd * 48.0 * sharp);',
  '    col = sc * (core * (0.5 + 2.0 * mag) + halo * 0.35 * mag);',
  '  }',
  '  return col;',
  '}',
  '',
  'vec3 starField(vec3 d) {',
  '  vec3 col = starLayer(d, 75.0, 0.0, 0.10, 1.0);',
  '  col += starLayer(d, 165.0, 53.7, 0.06, 1.5) * 0.75;',
  '  if (uNebula > 0.002) {',
  '    // 淡淡的银河带与星际云气',
  '    float band = exp(-pow(abs(d.y * 1.35 + 0.22), 2.0) * 1.7);',
  '    float n = fbm3(d * 3.1 + 4.0);',
  '    float n2 = vnoise(d * 7.7 + 9.0);',
  '    vec3 tint = mix(vec3(0.09, 0.11, 0.22), vec3(0.20, 0.10, 0.13), clamp(n2 * 1.4 - 0.2, 0.0, 1.0));',
  '    float amount = pow(max(n - 0.38, 0.0) * 2.0, 1.7);',
  '    col += tint * amount * (0.30 + band * 0.9) * uNebula;',
  '  }',
  '  return col * uStarBright * 1.4;',
  '}',
  '',
  '/* ---- 主光线步进 ---- */',
  'void main() {',
  '  vec2 ndc = vUv * 2.0 - 1.0;',
  '  vec3 rd = normalize(uCamFwd',
  '      + uCamRight * (ndc.x * uAspect * uTanHalfFov)',
  '      + uCamUp * (ndc.y * uTanHalfFov));',
  '  vec3 ro = uCamPos;',
  '',
  '  // 盘面倾角：把相机变换到"盘坐标系"（盘固定在 y=0 平面）',
  '  mat3 tiltM = rotX(uTilt);',
  '  ro = tiltM * ro;',
  '  rd = tiltM * rd;',
  '',
  '  float rs = uMass;',
  '  float ri = uDiskInner * rs;',
  '  float rOut = uDiskOuter * rs;',
  '  float escapeR = max(rOut * 2.2, 30.0 * rs);',
  '',
  '  vec3 pos = ro;',
  '  vec3 vel = rd;',
  '  vec3 hv = cross(pos, vel);',
  '  float h2 = dot(hv, hv);   // 比角动量守恒（加速度恒沿径向）',
  '',
  '  vec3 col = vec3(0.0);',
  '  float trans = 1.0;        // 透射率（吸积盘消光）',
  '  bool captured = false;',
  '  bool escapedClean = false;',
  '',
  '  int maxSteps = uSteps;',
  '  for (int i = 0; i < 640; i++) {',
  '    if (i >= maxSteps) break;',
  '    if (trans < 0.004) break;',
  '    float r2 = dot(pos, pos);',
  '    float r = sqrt(r2);',
  '    if (r < rs) { captured = true; break; }            // 落入事件视界',
  '    if (r > escapeR && dot(pos, vel) > 0.0) { escapedClean = true; break; }',
  '',
  '    // 自适应步长：靠近视界细化，远处放大',
  '    float dt = clamp(0.10 * (r - rs) + 0.015 * rs, 0.015 * rs, 2.2 * rs);',
  '',
  '    vec3 prev = pos;',
  '    vec3 accel = (-1.5 * uLensing * rs * h2 / (r2 * r2 * r)) * pos;',
  '    vel += accel * dt;',
  '    pos += vel * dt;',
  '',
  '    // 穿越盘面（y=0）检测 + 线性插值求精确交点',
  '    if (prev.y * pos.y < 0.0 && trans > 0.01) {',
  '      float tt = prev.y / (prev.y - pos.y);',
  '      vec3 ip = mix(prev, pos, tt);',
  '      float ir = length(ip.xz);',
  '      if (ir > ri && ir < rOut) {',
  '        vec4 s = sampleDisk(ip, ir, vel, rs, ri, rOut);',
  '        col += s.rgb * trans;',
  '        trans *= exp(-min(s.a * 1.2, 12.0));',
  '        if (trans < 0.004) { trans = 0.0; break; }',
  '      }',
  '    }',
  '  }',
  '',
  '  // 步数耗尽且仍在强场区 → 视为被捕获（避免阴影内漏出星光）',
  '  if (!captured && !escapedClean && length(pos) < 2.5 * rs) captured = true;',
  '',
  '  if (!captured && trans > 0.003) {',
  '    col += starField(normalize(vel)) * trans;',
  '  }',
  '',
  '  fragColor = vec4(max(col, vec3(0.0)), 1.0);',
  '}'
].join('\n');

/* ---------- 泛光：亮度阈值提取 ---------- */
var FS_BRIGHT = [
  '#version 300 es',
  'precision highp float;',
  'in vec2 vUv;',
  'out vec4 fragColor;',
  'uniform sampler2D tSrc;',
  'uniform vec2 uTexel;',
  'uniform float uThreshold;',
  'uniform float uKnee;',
  'void main() {',
  '  vec3 c = texture(tSrc, vUv).rgb;',
  '  c += texture(tSrc, vUv + vec2( uTexel.x,  uTexel.y)).rgb;',
  '  c += texture(tSrc, vUv + vec2(-uTexel.x,  uTexel.y)).rgb;',
  '  c += texture(tSrc, vUv + vec2( uTexel.x, -uTexel.y)).rgb;',
  '  c *= 0.25;',
  '  float l = dot(c, vec3(0.2126, 0.7152, 0.0722));',
  '  float k = smoothstep(uThreshold, uThreshold + uKnee, l);',
  '  fragColor = vec4(c * k, 1.0);',
  '}'
].join('\n');

/* ---------- 泛光：可分离高斯模糊（9-tap 线性采样优化） ---------- */
var FS_BLUR = [
  '#version 300 es',
  'precision highp float;',
  'in vec2 vUv;',
  'out vec4 fragColor;',
  'uniform sampler2D tSrc;',
  'uniform vec2 uDir;',
  'void main() {',
  '  vec3 sum = texture(tSrc, vUv).rgb * 0.227027;',
  '  vec2 o1 = uDir * 1.3846;',
  '  vec2 o2 = uDir * 3.2308;',
  '  sum += (texture(tSrc, vUv + o1).rgb + texture(tSrc, vUv - o1).rgb) * 0.316216;',
  '  sum += (texture(tSrc, vUv + o2).rgb + texture(tSrc, vUv - o2).rgb) * 0.070270;',
  '  fragColor = vec4(sum, 1.0);',
  '}'
].join('\n');

/* ---------- 合成：泛光叠加 + 宽银幕眩光 + ACES 色调映射 + 暗角 + 胶片颗粒 ---------- */
var FS_COMPOSITE = [
  '#version 300 es',
  'precision highp float;',
  'in vec2 vUv;',
  'out vec4 fragColor;',
  'uniform sampler2D tScene;',
  'uniform sampler2D tBloom1;',
  'uniform sampler2D tBloom2;',
  'uniform sampler2D tBloom3;',
  'uniform sampler2D tStreak;',
  'uniform float uBloom;',
  'uniform float uStreak;',
  'uniform float uExposure;',
  'uniform float uVignette;',
  'uniform float uGrain;',
  'uniform float uTime;',
  '',
  'vec3 aces(vec3 x) {',
  '  return clamp((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14), 0.0, 1.0);',
  '}',
  '',
  'void main() {',
  '  vec3 base = texture(tScene, vUv).rgb;',
  '  vec3 bloom = texture(tBloom1, vUv).rgb * 0.50',
  '             + texture(tBloom2, vUv).rgb * 0.30',
  '             + texture(tBloom3, vUv).rgb * 0.20;',
  '  vec3 c = base + bloom * uBloom * 1.6;',
  '  c += texture(tStreak, vUv).rgb * vec3(1.0, 0.85, 0.65) * uStreak;',
  '  c *= uExposure;',
  '  vec2 q = vUv - 0.5;',
  '  c *= clamp(1.0 - uVignette * dot(q, q) * 1.9, 0.0, 1.0);',
  '  c = aces(c);',
  '  float g = fract(sin(dot(vUv + fract(uTime), vec2(12.9898, 78.233))) * 43758.5453);',
  '  c += (g - 0.5) * uGrain;',
  '  c = pow(max(c, vec3(0.0)), vec3(1.0 / 2.2));   // 线性 → sRGB',
  '  fragColor = vec4(c, 1.0);',
  '}'
].join('\n');
